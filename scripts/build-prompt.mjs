#!/usr/bin/env node
// Rebuilds the shared prompts from context/*.md.
//   node scripts/build-prompt.mjs
//
// Outputs:
//   CLAUDE.md                 -> read automatically by Claude Code (imports every context file)
//   prompt/TEAM_PROMPT.md     -> everything (challenge, decisions, product, everyone's thinking).
//                                Paste into a claude.ai Project / ChatGPT / any chat.
//   prompt/APP_PROMPT.md      -> only what the website's AI should see (no team chatter)
//   prompt/systemPrompt.js    -> `export const APP_PROMPT, TEAM_PROMPT` for the website code
//   prompt/systemPrompt.json  -> same, for non-JS backends (Python etc.)

import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const ctxDir = join(root, "context");
const outDir = join(root, "prompt");
mkdirSync(outDir, { recursive: true });

// Which context files the website's AI gets. Everything else stays team-only.
const APP_FILES = ["02-product.md", "10-app-advisor.md"];

const files = readdirSync(ctxDir).filter((f) => f.endsWith(".md")).sort();
const read = (f) => readFileSync(join(ctxDir, f), "utf8").trim();

const header = (title) =>
  `<!-- AUTO-GENERATED by scripts/build-prompt.mjs — edit files in context/, not this file. -->\n# ${title}\n`;

const team =
  header("Hack the Lease — Team Context") +
  "\nYou are helping a two-person team build a hackathon project. The sections below are the team's live shared context. " +
  "Files named thinking-<name>.md are each teammate's current thinking; 01-decisions.md is what the team has agreed. " +
  "If a teammate's thinking conflicts with a recorded decision, point it out instead of silently picking one.\n\n" +
  files.map((f) => `---\n<!-- source: context/${f} -->\n${read(f)}`).join("\n\n") +
  "\n";

const appFiles = files.filter((f) => APP_FILES.includes(f));
const app =
  header("Hack the Lease — App System Prompt") +
  "\n" +
  appFiles.map((f) => read(f)).join("\n\n---\n\n") +
  "\n";

const claudeMd =
  "<!-- AUTO-GENERATED by scripts/build-prompt.mjs — edit files in context/, not this file. -->\n" +
  "# Hack the Lease\n\n" +
  "Shared team context for Claude Code. Each file below is imported automatically; " +
  "edit the files in context/ and run `npm run prompt` (or just push — CI rebuilds it).\n\n" +
  "When you learn something the team should keep (a decision, a new constraint), suggest adding it to context/01-decisions.md.\n\n" +
  files.map((f) => `@context/${f}`).join("\n") +
  "\n";

writeFileSync(join(outDir, "TEAM_PROMPT.md"), team);
writeFileSync(join(outDir, "APP_PROMPT.md"), app);
writeFileSync(
  join(outDir, "systemPrompt.js"),
  "// AUTO-GENERATED by scripts/build-prompt.mjs — edit files in context/, not this file.\n" +
    `export const APP_PROMPT = ${JSON.stringify(app)};\n` +
    `export const TEAM_PROMPT = ${JSON.stringify(team)};\n`
);
writeFileSync(join(outDir, "systemPrompt.json"), JSON.stringify({ APP_PROMPT: app, TEAM_PROMPT: team }, null, 2) + "\n");
writeFileSync(join(root, "CLAUDE.md"), claudeMd);

console.log(`Built prompts from ${files.length} context files: ${files.join(", ")}`);
